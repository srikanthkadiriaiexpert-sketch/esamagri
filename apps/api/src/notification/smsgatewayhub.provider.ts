import { Inject, Injectable, Logger } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { createHash } from 'node:crypto';
import type { ApiEnv } from '@esamagri/config';

/**
 * SMS Gateway Hub — TRANSPORT ONLY.
 *
 * This file does exactly one thing: hand a finished message to SMS
 * Gateway Hub over HTTPS and report, honestly, what the gateway said
 * about it. It does not generate, hash, store, expire, count or verify
 * an OTP, and it does not compose the message either — OtpSmsService
 * owns the approved DLT wording and passes the finished text in. The
 * code is still generated by OtpService (CSPRNG), still stored only as
 * HMAC-SHA256(OTP_HASH_PEPPER, code) in shared.otp_requests, and still
 * verified locally in constant time by CustomerAuthService. The
 * provider's own AUTOGEN/VERIFY style of flow is deliberately NOT
 * adopted, for the reasons set out in @esamagri/config's api-env.ts.
 *
 * WHICH REQUEST FORMAT, AND WHY IT CHANGED.
 *
 * This was a POST of a raw XML body to /api/mt/SendSms, because that was
 * the only form the vendor's 11-page HTTP API document showed end to end
 * (pages 9-10: a complete body and a captured 200 OK). It never
 * delivered a message. The reason was not the transport: that document
 * contains NO Entity ID and NO Content Template ID field anywhere, so
 * the XML carried neither, and DLT scrubbing has nothing to match a
 * message against without them.
 *
 * SMS Gateway Hub support supplied the GET form of SendSMS, which
 * carries both. A live send using it was accepted by the gateway and
 * ARRIVED ON A HANDSET — which is why this file is now GET. That is the
 * evidence the change rests on: not a reading of the document, but a
 * delivered message.
 *
 * WHAT THE DIAGNOSIS COST, RECORDED SO IT IS NOT REPEATED. The failing
 * requests answered ErrorCode 007, "username or password is invalid",
 * and that was a red herring twice over. The key was never wrong: the
 * same key is accepted by GetDelivery, getsenderid and gettemplates. And
 * 007 is not credential-specific on this account — GetBalance answers it
 * for a deliberately invalid key AND for the real one. It is a catch-all
 * refusal. Reading it as "wrong API key" nearly led to regenerating a
 * working credential.
 *
 * THE ENDPOINT IS FIXED, NOT CONFIGURABLE. It carries the API key, and
 * a URL read from configuration is a URL that a mistake — or an edited
 * .env — can point at someone else's server. There is no
 * SMS_GATEWAY_HUB_BASE_URL for that reason.
 *
 * A GET PUTS THE API KEY IN THE URL, which is a real downgrade: URLs
 * reach access logs and proxy logs in a way request bodies do not. It is
 * accepted here only because it is the form the provider documents and
 * the only one proven to deliver. The mitigation is that this file never
 * logs the URL, and the one place a fetch error could carry it is
 * summarised rather than interpolated — see the catch below.
 *
 * NEVER THROWS. Every path returns a result object. A gateway outage
 * must not change what a sign-in looks like from outside; see
 * CustomerAuthService, which audits a failure and deliberately does not
 * propagate it, so that an SMS problem cannot become an
 * account-enumeration oracle.
 *
 * NOTHING SECRET REACHES A LOG LINE. The request URL now contains both
 * the API key and the OTP, so THE URL is never logged — not at debug
 * level, not on failure, not in an error message. That matters more
 * under GET than it did under POST, because a URL is the thing libraries
 * and proxies are most likely to echo. What is logged is the
 * recipient hash (sha256, first 16 hex — the same scheme
 * CustomerAuthService.hashForAudit uses, so a log line and an audit row
 * can be matched up without either holding a phone number), the
 * gateway's ErrorCode, and its short ErrorMessage.
 */

/**
 * The GET SendSMS endpoint supplied by SMS Gateway Hub support, and the
 * one a live send was delivered through.
 *
 * NOTE THE CASING: `SendSMS`, not the `SendSms` of the XML API. Both
 * resolve on the provider's stack, but this is the spelling support gave
 * and the spelling that was proven, so it is the spelling used.
 */
export const SMS_GATEWAY_HUB_ENDPOINT = 'https://www.smsgatewayhub.com/api/mt/SendSMS';

/**
 * Page 10: FlashSms 0 = a normal SMS. A flash message appears on the
 * screen without being saved, which is wrong for a code someone needs
 * to read and type. It is a constant rather than a setting because
 * there is no circumstance in which an OTP should be sent any other
 * way.
 */
const FLASH_SMS = '0';

/** Success, once normalised by normaliseErrorCode below. */
const SUCCESS_ERROR_CODE = '000';

/**
 * Puts a gateway ErrorCode into the zero-padded three-digit form page
 * 11's table uses, because THE GATEWAY DOES NOT ALWAYS SEND IT THAT WAY.
 *
 * This was found the hard way. A live balance enquiry answered
 * `"ErrorCode":"7"` — the same failure page 11 lists as `007`,
 * "username or password is invalid". The document is inconsistent with
 * itself about this: the error table is zero-padded throughout, while
 * the GetDelivery and GetBalance examples on page 7 show success as
 * `"0"` rather than `"000"`. The live reply settles it — codes arrive
 * unpadded, at least from some endpoints.
 *
 * Before this existed, an unpadded code missed the lookup table and was
 * recorded as the catch-all PROVIDER_REJECTED. That is a quiet,
 * expensive kind of wrong: the gateway said "your credentials are
 * invalid", a sentence that names the fix, and the audit log recorded
 * "the gateway said no" instead. Normalising here is what makes an
 * operator's first question answerable from the audit log alone.
 *
 * A non-numeric code is returned unchanged rather than mangled — the
 * lookup will miss it and PROVIDER_REJECTED is then the honest answer.
 */
export function normaliseErrorCode(raw: string): string {
  const trimmed = raw.trim();
  if (!/^\d+$/.test(trimmed)) return trimmed;
  // "007" -> "7", "000" -> "0", "7" -> "7"; then pad back to three.
  return trimmed.replace(/^0+(?=\d)/, '').padStart(3, '0');
}

/**
 * Safe, internal failure reasons. These are what reach
 * shared.audit_log; the gateway's own response is never handed to a
 * customer, and never returned from the API.
 */
export type SmsGatewayHubFailureReason =
  /**
   * One of the four required settings is absent from configuration — the
   * API key, the sender ID, the DLT Entity ID or the DLT Content
   * Template ID. Nothing was sent.
   */
  | 'NOT_CONFIGURED'
  /** The number could not be put into the 91XXXXXXXXXX form the gateway wants. */
  | 'INVALID_RECIPIENT'
  /**
   * THESE FOUR WERE ONE REASON, 'PROVIDER_AUTH', AND THAT WAS A MISTAKE
   * THAT COST REAL TIME.
   *
   * Seven gateway codes mean "we will not accept this account's
   * request", and lumping them together produced an audit row that
   * said so and nothing more. But the seven need opposite responses —
   * a rejected key is fixed in the provider's panel, an unregistered
   * IP is fixed by registering the address, a restricted API is a
   * permission the account does not have — and the audit log records
   * only the reason, not the gateway's number. So the one record that
   * survives a closed console window named a category instead of a
   * cause, and the cause could not be recovered afterwards at all.
   *
   * Split, each of these names something an operator can act on
   * without reading a log.
   */
  /** 001, 007 — the API key itself was not accepted. */
  | 'PROVIDER_KEY_REJECTED'
  /** 008, 009, 014 — the account is inactive or locked. */
  | 'PROVIDER_ACCOUNT_BLOCKED'
  /** 010 — this API is not permitted on this account. */
  | 'PROVIDER_API_RESTRICTED'
  /** 011 — the gateway's optional IP allowlist (vendor document p.5)
   *  does not include the address this request came from. */
  | 'PROVIDER_IP_NOT_ALLOWED'
  /** 015 — the sender ID is not valid for this account. */
  | 'PROVIDER_SENDER_ID'
  /** 024 — DLT template mismatch. See the note in otp-sms.service.ts. */
  | 'PROVIDER_TEMPLATE'
  /** 021 — the account is out of credits. */
  | 'PROVIDER_CREDITS'
  /** 013/017/018/019/020/023/025/026/027 — the request itself was wrong. */
  | 'PROVIDER_REQUEST'
  /** A non-zero ErrorCode that is not in the table above. */
  | 'PROVIDER_REJECTED'
  /** The gateway answered with a non-2xx HTTP status. */
  | 'PROVIDER_UNAVAILABLE'
  /** 2xx, but the body was not JSON, or carried no usable ErrorCode. */
  | 'MALFORMED_RESPONSE'
  /** SMS_GATEWAY_HUB_TIMEOUT_MS elapsed with no reply. */
  | 'TIMEOUT'
  /** DNS, TLS or socket failure — the request never completed. */
  | 'NETWORK';

export type SmsGatewayHubResult =
  | { status: 'SENT'; jobId: string | null; messageId: string | null }
  | { status: 'FAILED'; reason: SmsGatewayHubFailureReason; errorCode: string | null };

/**
 * Page 11's error table, mapped to the reasons above. Grouped by what
 * an operator would actually have to DO about each one, which is why
 * 007 and 011 share a reason: both mean "the gateway will not accept
 * this account's requests until something is changed in the panel".
 */
const ERROR_CODE_REASONS: Readonly<Record<string, SmsGatewayHubFailureReason>> = {
  '001': 'PROVIDER_KEY_REJECTED', // login details cannot be blank
  '003': 'PROVIDER_REQUEST', // sender cannot be blank
  '004': 'PROVIDER_REQUEST', // message text cannot be blank
  '005': 'PROVIDER_REQUEST', // message data cannot be blank
  '006': 'PROVIDER_REJECTED', // generic error description
  '007': 'PROVIDER_KEY_REJECTED', // username or password is invalid
  '008': 'PROVIDER_ACCOUNT_BLOCKED', // account not active
  '009': 'PROVIDER_ACCOUNT_BLOCKED', // account locked, contact your account manager
  '010': 'PROVIDER_API_RESTRICTED', // api restriction
  '011': 'PROVIDER_IP_NOT_ALLOWED', // ip address restriction
  '012': 'PROVIDER_REQUEST', // invalid length of message text
  '013': 'PROVIDER_REQUEST', // mobile numbers not valid
  '014': 'PROVIDER_ACCOUNT_BLOCKED', // account locked due to spam message
  '015': 'PROVIDER_SENDER_ID', // senderid not valid
  '017': 'PROVIDER_REQUEST', // groupid not valid
  '018': 'PROVIDER_REQUEST', // multi message to group is not supported
  '019': 'PROVIDER_REQUEST', // schedule date is not valid
  '020': 'PROVIDER_REQUEST', // message or mobile number cannot be blank
  '021': 'PROVIDER_CREDITS', // insufficient credits
  '022': 'PROVIDER_REQUEST', // invalid jobid
  '023': 'PROVIDER_REQUEST', // parameter missing
  '024': 'PROVIDER_TEMPLATE', // invalid template or template mismatch
  '025': 'PROVIDER_REQUEST', // {Field} can not be blank or empty
  '026': 'PROVIDER_REQUEST', // invalid date range
  '027': 'PROVIDER_REQUEST', // invalid optin user
};

@Injectable()
export class SmsGatewayHubProvider {
  private readonly logger = new Logger(SmsGatewayHubProvider.name);

  constructor(@Inject(ConfigService) private readonly config: ConfigService<ApiEnv, true>) {}

  /**
   * Whether the two settings without which nothing can be sent are
   * present. Checked before the request is built so that a missing
   * credential produces NOT_CONFIGURED — a reason an operator can act
   * on — rather than a 007 from the gateway, which reads like a wrong
   * key rather than an absent one. The values themselves are never
   * read out, logged or returned.
   */
  isConfigured(): boolean {
    return Boolean(
      this.apiKey() && this.senderId() && this.entityId() && this.dltTemplateId()
    );
  }

  /**
   * Sends one message to one number. `messageText` is already composed
   * and already contains the OTP, so it is never logged.
   */
  async send(mobileNumber: string, messageText: string): Promise<SmsGatewayHubResult> {
    const recipient = this.recipientHash(mobileNumber);

    const apiKey = this.apiKey();
    const senderId = this.senderId();
    const entityId = this.entityId();
    const dltTemplateId = this.dltTemplateId();
    if (!apiKey || !senderId || !entityId || !dltTemplateId) {
      // Names which setting is absent, never what any of them contains.
      //
      // THE DLT PAIR IS CHECKED HERE TOO, not only in the config schema.
      // A request missing either is accepted by the gateway and then
      // dropped by DLT scrubbing, so it would be recorded as SENT and
      // deliver nothing. Refusing locally turns that into
      // NOT_CONFIGURED, which names the fix.
      const missing = [
        !apiKey && 'SMS_GATEWAY_HUB_API_KEY',
        !senderId && 'SMS_GATEWAY_HUB_SENDER_ID',
        !entityId && 'SMS_GATEWAY_HUB_ENTITY_ID',
        !dltTemplateId && 'SMS_GATEWAY_HUB_DLT_TEMPLATE_ID',
      ]
        .filter(Boolean)
        .join(', ');
      this.logger.error(
        `SMS Gateway Hub is selected but not configured (missing: ${missing}). ` +
          `NOTHING WAS SENT. recipient=${recipient}`
      );
      return { status: 'FAILED', reason: 'NOT_CONFIGURED', errorCode: null };
    }

    const number = normaliseIndianMobile(mobileNumber);
    if (number === null) {
      this.logger.error(
        `SMS Gateway Hub: the recipient is not a mobile number this gateway can accept, ` +
          `so NOTHING WAS SENT. recipient=${recipient}`
      );
      return { status: 'FAILED', reason: 'INVALID_RECIPIENT', errorCode: null };
    }

    const url = buildSendSmsUrl({
      apiKey,
      senderId,
      channel: this.setting('SMS_GATEWAY_HUB_CHANNEL', '2'),
      dcs: this.setting('SMS_GATEWAY_HUB_DCS', '0'),
      route: this.setting('SMS_GATEWAY_HUB_ROUTE', '1'),
      number,
      text: messageText,
      entityId,
      dltTemplateId,
    });

    const timeoutMs = this.timeoutMs();
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), timeoutMs);

    let response: Response;
    try {
      response = await fetch(url, {
        method: 'GET',
        headers: { accept: 'application/json' },
        signal: controller.signal,
      });
    } catch (error) {
      // An abort and a socket failure are different problems with
      // different fixes, so they are told apart rather than lumped
      // together as "network". The error is summarised, never
      // interpolated whole: it can carry the request URL.
      const aborted = controller.signal.aborted;
      this.logger.error(
        aborted
          ? `SMS Gateway Hub did not answer within ${timeoutMs}ms; NOTHING CONFIRMED SENT. recipient=${recipient}`
          : `SMS Gateway Hub could not be reached (${describeError(error)}); ` +
              `NOTHING SENT. recipient=${recipient}`
      );
      return {
        status: 'FAILED',
        reason: aborted ? 'TIMEOUT' : 'NETWORK',
        errorCode: null,
      };
    } finally {
      clearTimeout(timer);
    }

    if (!response.ok) {
      this.logger.error(
        `SMS Gateway Hub answered HTTP ${response.status}; NOTHING CONFIRMED SENT. recipient=${recipient}`
      );
      return { status: 'FAILED', reason: 'PROVIDER_UNAVAILABLE', errorCode: null };
    }

    let payload: unknown;
    try {
      payload = JSON.parse(await response.text());
    } catch {
      // Deliberately does not include the body: a gateway that returns
      // something unexpected could return anything at all, including a
      // reflection of the request.
      this.logger.error(
        `SMS Gateway Hub answered HTTP ${response.status} with a body that is not JSON; ` +
          `NOTHING CONFIRMED SENT. recipient=${recipient}`
      );
      return { status: 'FAILED', reason: 'MALFORMED_RESPONSE', errorCode: null };
    }

    const errorCode = readString(payload, 'ErrorCode');
    if (errorCode === null) {
      this.logger.error(
        `SMS Gateway Hub answered JSON with no ErrorCode; NOTHING CONFIRMED SENT. recipient=${recipient}`
      );
      return { status: 'FAILED', reason: 'MALFORMED_RESPONSE', errorCode: null };
    }

    // HTTP 200 ALONE IS NOT ACCEPTANCE. Every documented failure on
    // page 11 arrives as a 200 with a non-zero ErrorCode, so this is
    // the only check that distinguishes a queued message from a
    // rejected one. The code is normalised first — see
    // normaliseErrorCode for why an unpadded "7" must not be allowed to
    // miss the table.
    const normalised = normaliseErrorCode(errorCode);
    if (normalised !== SUCCESS_ERROR_CODE) {
      const reason = ERROR_CODE_REASONS[normalised] ?? 'PROVIDER_REJECTED';
      this.logger.error(
        `SMS Gateway Hub REJECTED the message: ErrorCode=${normalised} ` +
          `(as sent: ${errorCode.trim()}) (${summarise(readString(payload, 'ErrorMessage'))}) ` +
          `reason=${reason}. NOTHING WAS DELIVERED. recipient=${recipient}`
      );
      return { status: 'FAILED', reason, errorCode };
    }

    const jobId = readString(payload, 'JobId');
    const messageId = readFirstMessageId(payload);

    // ACCEPTED, NOT DELIVERED. The gateway has taken the message; it
    // has not told us the handset received it. The delivery-report API
    // (page 7) is what answers that, and is not called here — a
    // one-time code is not worth holding a sign-in open to poll for.
    this.logger.log(
      `SMS Gateway Hub accepted the message for delivery. ` +
        `jobId=${jobId ?? 'none'} recipient=${recipient}`
    );
    return { status: 'SENT', jobId, messageId };
  }

  private apiKey(): string {
    return (this.config.get('SMS_GATEWAY_HUB_API_KEY', { infer: true }) ?? '').trim();
  }

  private senderId(): string {
    return (this.config.get('SMS_GATEWAY_HUB_SENDER_ID', { infer: true }) ?? '').trim();
  }

  /**
   * The DLT Principal Entity ID and Content Template ID.
   *
   * Not secrets — they are registration identifiers the provider's own
   * getsenderid and gettemplates APIs return in plain text — but they are
   * not logged either, because nothing here needs to log them and a
   * value that is never printed cannot be printed by mistake later.
   */
  private entityId(): string {
    return (this.config.get('SMS_GATEWAY_HUB_ENTITY_ID', { infer: true }) ?? '').trim();
  }

  private dltTemplateId(): string {
    return (this.config.get('SMS_GATEWAY_HUB_DLT_TEMPLATE_ID', { infer: true }) ?? '').trim();
  }

  private timeoutMs(): number {
    const configured = this.config.get('SMS_GATEWAY_HUB_TIMEOUT_MS', { infer: true });
    return typeof configured === 'number' && configured > 0 ? configured : 10_000;
  }

  /**
   * One of the three routing scalars, falling back to the documented
   * default if configuration is somehow absent. They are strings rather
   * than numbers on purpose: page 3 of the vendor document hints at a
   * non-numeric channel value for OTP traffic ("for OTP = OTP"), which
   * page 10 contradicts, and the provider's own panel reports the
   * successful send's channel as "Trans" rather than "2". Keeping them
   * free strings means that if SMS Gateway Hub confirms a different
   * value, it is a .env edit and not a code change.
   */
  private setting(key: 'SMS_GATEWAY_HUB_CHANNEL' | 'SMS_GATEWAY_HUB_DCS' | 'SMS_GATEWAY_HUB_ROUTE', fallback: string): string {
    const value = this.config.get(key, { infer: true });
    return typeof value === 'string' && value.trim() !== '' ? value.trim() : fallback;
  }

  /** sha256, first 16 hex — identical to CustomerAuthService.hashForAudit. */
  private recipientHash(mobileNumber: string): string {
    return createHash('sha256').update(mobileNumber).digest('hex').slice(0, 16);
  }
}

/**
 * The parameter names the GET SendSMS API takes, exactly as SMS Gateway
 * Hub support supplied them.
 *
 * THE CASING IS MIXED AND IT IS NOT A TYPO: `APIKey`, `DCS` and
 * `EntityId` are capitalised while `senderid`, `channel`, `flashsms`,
 * `number`, `text`, `route` and `dlttemplateid` are lower case. That is
 * what was supplied and what was proven to deliver, so it is reproduced
 * verbatim. In a query string the names are case-sensitive, so
 * "tidying" them is a change that would stop delivery.
 */
export const SEND_SMS_PARAM_NAMES = [
  'APIKey',
  'senderid',
  'channel',
  'DCS',
  'flashsms',
  'number',
  'text',
  'route',
  'EntityId',
  'dlttemplateid',
] as const;

/**
 * Builds the GET SendSMS URL.
 *
 * ENCODING IS DONE BY URLSearchParams, NOT BY HAND. Every value is
 * percent-encoded by the platform, which is what makes the message text
 * safe to carry: the approved wording contains spaces, full stops and a
 * hyphen, and a future template could contain an `&` — which,
 * unencoded, would end the `text` parameter early and silently send a
 * truncated message. Hand-rolled escaping is exactly what the previous
 * XML implementation had to get right, and there is no reason to repeat
 * that risk when the platform does it correctly.
 *
 * The API key is encoded the same way, so a key containing `+` or `/`
 * cannot be mangled in transit.
 *
 * NO VALUE IS DROPPED OR DEFAULTED HERE. A blank parameter is a caller
 * error, and `send` has already refused the request before reaching
 * this function.
 */
export function buildSendSmsUrl(params: {
  apiKey: string;
  senderId: string;
  channel: string;
  dcs: string;
  route: string;
  number: string;
  text: string;
  entityId: string;
  dltTemplateId: string;
}): string {
  const query = new URLSearchParams({
    APIKey: params.apiKey,
    senderid: params.senderId,
    channel: params.channel,
    DCS: params.dcs,
    flashsms: FLASH_SMS,
    number: params.number,
    text: params.text,
    route: params.route,
    EntityId: params.entityId,
    dlttemplateid: params.dltTemplateId,
  });
  return `${SMS_GATEWAY_HUB_ENDPOINT}?${query.toString()}`;
}

/**
 * Puts a number into the 91XXXXXXXXXX form every example on pages 2-10
 * uses: country code, no plus sign, no spaces. Returns null rather than
 * guessing when the input is not an Indian mobile number — the gateway
 * would answer 013 for it anyway, and a local refusal costs nothing and
 * says so more clearly.
 *
 * This normalisation is for the gateway only. It does not touch how the
 * number is stored, matched or verified anywhere else: shared.customers
 * holds +919XXXXXXXXX and CustomerAuthService still canonicalises for
 * itself, unchanged.
 */
export function normaliseIndianMobile(mobileNumber: string): string | null {
  const digits = (mobileNumber ?? '').replace(/\D/g, '');
  if (/^[6-9]\d{9}$/.test(digits)) return `91${digits}`;
  if (/^91[6-9]\d{9}$/.test(digits)) return digits;
  if (/^0[6-9]\d{9}$/.test(digits)) return `91${digits.slice(1)}`;
  return null;
}

function readString(payload: unknown, key: string): string | null {
  if (typeof payload !== 'object' || payload === null) return null;
  const value = (payload as Record<string, unknown>)[key];
  if (typeof value === 'string') return value;
  if (typeof value === 'number') return String(value);
  return null;
}

function readFirstMessageId(payload: unknown): string | null {
  if (typeof payload !== 'object' || payload === null) return null;
  const data = (payload as Record<string, unknown>).MessageData;
  if (!Array.isArray(data) || data.length === 0) return null;
  return readString(data[0], 'MessageId');
}

/**
 * The gateway's own ErrorMessage, trimmed to a length that cannot turn
 * a log line into a dump. It is provider text ("Success", "senderid not
 * valid"), never ours, so it carries no key and no code — but it is
 * bounded anyway, because an unexpected body could put anything here.
 */
function summarise(message: string | null): string {
  if (message === null) return 'no message';
  const flattened = message.replace(/\s+/g, ' ').trim();
  return flattened.length > 120 ? `${flattened.slice(0, 120)}…` : flattened;
}

/**
 * A short description of a thrown value: the error's NAME, plus the
 * underlying system code when there is one ('ENOTFOUND', 'ECONNRESET',
 * 'UNABLE_TO_VERIFY_LEAF_SIGNATURE'), which is the part an operator
 * actually needs. The error's MESSAGE is deliberately not used —
 * undici's messages quote the request, and under GET the request URL
 * holds both the API key and the OTP. This was already the rule when
 * those sat in a POST body; it is load-bearing now that they are in the
 * URL, which is the part a library is most likely to echo.
 */
function describeError(error: unknown): string {
  if (!(error instanceof Error)) return typeof error;
  const cause = (error as { cause?: unknown }).cause;
  const code =
    typeof cause === 'object' && cause !== null && typeof (cause as { code?: unknown }).code === 'string'
      ? (cause as { code: string }).code
      : null;
  const name = error.name || 'Error';
  return code === null ? name : `${name}: ${code}`;
}
