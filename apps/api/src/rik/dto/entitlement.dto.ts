import { IsArray, IsBoolean, IsNumber, IsOptional, IsString, IsUUID, Length, Min, IsIn } from 'class-validator';

/**
 * Request shapes for the RIK entitlement API.
 *
 * Note what is absent: no dietary preference, no eligible days, no
 * entitlement figure, no ratio. Those are resolved server-side from
 * authoritative data. A client can say WHAT it wants, never WHAT IT IS
 * ENTITLED TO.
 */

export class SetProvisionQuantityDto {
  @IsUUID()
  provisionId!: string;

  /** Absolute quantity in the provision's own unit. Zero removes the line. */
  @IsNumber({ maxDecimalPlaces: 4 })
  @Min(0)
  quantity!: number;
}

export class SetElectionsDto {
  @IsArray()
  /**
   * Any UUID version, NOT version 4.
   *
   * Every id in this system is generated by `shared.uuid_generate_v7()`
   * — UUIDv7, chosen in Phase 2 for its time-ordered index locality.
   * Pinning this to version 4 meant the route rejected every real
   * conversion id with a validation error, so no client could ever
   * choose an alternative. Found in STEP 11D by calling the route over
   * HTTP for the first time; the STEP 11B suite reached the same logic
   * through the service, below the validation pipe, and so could not
   * see it. `SetProvisionQuantityDto` above was always version-neutral,
   * which is why quantities worked and elections did not.
   */
  @IsUUID(undefined, { each: true })
  @IsOptional()
  conversionIds?: string[];
}

/**
 * Confirming a ration selection.
 *
 * `availabilityAcknowledged` is a boolean the customer must send as
 * `true`, not a flag the server infers. The warning says a chosen
 * provision may not be there on the issue day, and an officer who has
 * not read that should not be recorded as having accepted it — so
 * merely reaching this endpoint is not acknowledgement, and the service
 * refuses anything but an explicit true.
 *
 * Note what is NOT here: no price, no total, no payment reference, no
 * tax. A RIK issue is an entitlement being drawn, not a purchase.
 *
 * Note also what is not here: no customer id. Identity comes from the
 * verified token, so a customer cannot confirm on behalf of another.
 */
export class ConfirmSelectionDto {
  @IsBoolean()
  availabilityAcknowledged!: boolean;

  @IsIn(['PICKUP', 'DELIVERY'])
  fulfillmentType!: 'PICKUP' | 'DELIVERY';

  /**
   * Required for PICKUP. Deliberately an id, never a name: the server
   * resolves the location and snapshots ITS name, so a client cannot
   * write its own text into the historical record.
   */
  @IsOptional()
  @IsUUID()
  pickupLocationId?: string;

  /**
   * Required for DELIVERY. A blank or whitespace-only address is
   * refused by the service, which trims before judging — the length
   * bound here is a shape guard, not the rule.
   */
  @IsOptional()
  @IsString()
  @Length(0, 1000)
  deliveryAddress?: string;
}

export class EntitlementQueryDto {
  @IsOptional()
  @IsUUID()
  periodId?: string;

  @IsOptional()
  @IsString()
  @IsIn(['FRESH', 'DRY'])
  issuePeriod?: 'FRESH' | 'DRY';
}
