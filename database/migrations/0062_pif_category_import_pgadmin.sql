-- ===========================================================================
-- Migration 0062: import the 164 approved PIF categories
-- ===========================================================================
--
-- WHAT THIS DOES. Inserts the approved category trees for the two PIF shops
-- into pif.categories: 19 main + 135 subcategories for Grocers, 2 main + 8
-- subcategories for Fresh Mart. 164 rows, INSERT ONLY.
--
-- WHAT THIS DOES NOT DO, DELIBERATELY. It does not touch the 14 legacy
-- category rows (business_slug IS NULL) that migrations 0019 and 0054 left
-- behind. It does not deactivate them, rename them, or repoint anything at
-- the new rows. Legacy cleanup is a separate migration, by decision. It
-- writes nothing at all to pif.products, pif.orders, pif.order_items, or to
-- any rik.* or shared.* object, and it asserts all of that after the fact.
--
-- WHERE THE DATA COMES FROM. apps/customer-web/src/lib/businesses/
-- category-tree.ts, which is generated by scripts/gen-categories.cjs and is
-- the approved source. Every slug below was re-derived from its name with
-- the single rule in apps/api/src/pif/services/category-slug.ts (lowercase;
-- & becomes "and"; punctuation becomes a hyphen) and matched the stored slug
-- in all 164 cases. Every image path below is the exact `src` from
-- category-images.ts with its BASE constant resolved, and all 164 files were
-- confirmed present under apps/customer-web/public/brands/.
--
-- STABLE IDS, AND WHY. Each row carries an explicit, hard-coded UUID instead
-- of letting shared.uuid_generate_v7() choose one. The rollback deletes by
-- that exact list of 164 primary keys and by nothing else -- never by
-- "business_slug IS NOT NULL", which would also destroy any category an
-- administrator adds after this migration. The ids are valid UUIDv7 values
-- sharing the marker groups -7062-8062-, so the batch is greppable:
--   01a1998e-4400-7062-8062-000000000001  .. -000000000021   the 21 mains
--   01a1998e-4400-7062-8062-000000000022  .. -000000000164   the 143 subs
--
-- IMAGE COLUMNS. image_ref and approved_image_ref are both set to the same
-- path. image_ref is the live value a staff member may later replace from
-- the Admin Portal; approved_image_ref is the protected original that
-- "restore approved artwork" restores from, and the upload API never writes
-- it. The paths resolve against the Customer App's existing convention --
-- files served from apps/customer-web/public, so /brands/... on disk is
-- /brands/... in the URL, exactly as categoryImage() already returns them.
--
-- TWO INSERT STATEMENTS, AND WHY. pif.trg_validate_category_parent() is a
-- FOR EACH ROW trigger that queries pif.categories to confirm a parent is
-- not itself a subcategory. The 21 mains are therefore inserted first and
-- committed to the snapshot the trigger reads before the 143 subcategories
-- reference them. A single mixed VALUES list would be fragile here.
--
-- HOW TO RUN IT. One statement, one transaction, no BEGIN and no COMMIT --
-- the DO block below is atomic by itself and either applies all 164 rows or
-- none. That is deliberate: migration 0059 reported success from inside a
-- transaction that was then rolled back, and this shape cannot do that.
-- There are no psql backslash meta-commands in this file, so unlike 0061 it
-- runs unchanged in psql AND in the pgAdmin Query Tool.
--
--   psql -U postgres -d esamagri_staging -v ON_ERROR_STOP=1 \
--        -f 0062_pif_category_import_pgadmin.sql
--
-- Do NOT add -1 (single transaction): the trailing verification queries are
-- meant to read committed state.
--
-- NO SET ROLE HERE, AND THAT IS DELIBERATE. pif.categories and pif.products
-- are owned by postgres, and esamagri_owner is NOLOGIN and owns nothing. A
-- SET ROLE esamagri_owner drops the session out of superuser, after which
-- information_schema -- which is privilege-filtered -- reports zero columns
-- on a table that is plainly there. That is what stopped migration 0061 on
-- its first attempt. Run this as postgres.
--
-- REVERSIBILITY. 0062_pif_category_import_rollback.sql deletes exactly these
-- 164 ids, subcategories before mains, and refuses if any product has since
-- been filed under one of them.
-- ===========================================================================

